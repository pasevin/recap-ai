import { Command, Flags } from '@oclif/core';
import { config } from '../utils/config';
import { LinearService } from '../services/linear';
import { OpenAIService, ActivityData } from '../services/openai';
import { FormatterService } from '../services/formatter';
import { postProcessorService } from '../services/post_processor';
import { createGitHubService } from '../services/service_factory';
import {
  GitHubFile,
  GitHubReview,
  GitHubPullRequest,
  GitHubIssue,
  GitHubLabel,
  GitHubUser,
} from '../interfaces/github-types';
import ora from 'ora';

export default class Summarize extends Command {
  static description = 'Generate an AI summary of GitHub and Linear activity';

  static examples = [
    '<%= config.bin %> summarize  # Concise AI summary for configured user',
    '<%= config.bin %> summarize --detailed  # Detailed summary with source references',
    '<%= config.bin %> summarize --author-github john@company.com --author-linear john@company.com  # Cross-service filtering',
    '<%= config.bin %> summarize --repo owner/repo  # Repository-specific activity',
    '<%= config.bin %> summarize --since 2024-01-01 --until 2024-01-31',
    '<%= config.bin %> summarize --format json  # Output raw data in JSON format',
    '<%= config.bin %> summarize --format markdown  # Output formatted markdown for web display',
  ];

  static flags = {
    since: Flags.string({
      char: 's',
      description:
        'Start date (YYYY-MM-DD). If not provided, uses default timeframe from config',
      required: false,
    }),
    until: Flags.string({
      char: 'u',
      description:
        'End date (YYYY-MM-DD). If not provided, uses default timeframe from config',
      required: false,
    }),
    'author-github': Flags.string({
      description:
        'GitHub username/email for filtering (must be used with --author-linear)',
      dependsOn: ['author-linear'],
    }),
    'author-linear': Flags.string({
      description:
        'Linear email address for filtering (must be used with --author-github)',
      dependsOn: ['author-github'],
    }),
    format: Flags.string({
      char: 'f',
      description: 'Output format (summary/markdown/json)',
      options: ['summary', 'markdown', 'json'],
      default: 'summary',
    }),
    repo: Flags.string({
      char: 'r',
      description:
        'Repository in the format owner/repo (limits search to specific repo)',
    }),
    detailed: Flags.boolean({
      char: 'd',
      description:
        'Use detailed formatting with structured sections and source references',
      default: false,
    }),
    perspective: Flags.string({
      char: 'p',
      options: ['first-person', 'third-person'],
      description:
        'Narrative perspective for the AI summary. When set to third-person, the summary uses the configured author name.',
    }),
    'perspective-name': Flags.string({
      description:
        'Custom display name to use when writing in third-person perspective. Overrides the configured author identifier.',
    }),
    'full-context': Flags.boolean({
      description:
        'Disable truncation and expand items; increases prompt size (Advanced Reports only).',
      default: false,
    }),
    'no-post': Flags.boolean({
      description:
        'Disable post-processing (leave URLs and Summary Statistics as generated by the LLM).',
      default: false,
    }),
    'template-id': Flags.string({
      description:
        'Template identifier to use for rendering the AI summary (e.g., default-standup-v1)',
      required: false,
    }),
  };

  async run(): Promise<void> {
    const { flags } = await this.parse(Summarize);

    // Get the default timeframe once
    const defaultTimeframe =
      (config.get('github.defaults.timeframe') as string) ?? '1w';

    // Get the GitHub user (from flag or config)
    const githubUser =
      flags['author-github'] ??
      config.get('github.defaults.person.identifier') ??
      config.get('github.defaults.author');

    if (!githubUser) {
      throw new Error(
        'No GitHub user specified. Use --author-github flag or set github.defaults.person.identifier in config'
      );
    }

    // Determine repository from flag or config (prefer flag)
    let githubOwner: string | undefined;
    let githubRepo: string | undefined;

    if (flags.repo) {
      const repoParts = flags.repo.split('/');
      if (repoParts.length !== 2) {
        throw new Error('Repository must be in the format owner/repo');
      }
      githubOwner = repoParts[0];
      githubRepo = repoParts[1];
    } else {
      const cfgOwner = config.get('github.owner') as string | undefined;
      const cfgRepo = config.get('github.repo') as string | undefined;
      const cfgCombined = config.get('github.defaults.repository') as
        | string
        | undefined;

      if (cfgOwner && cfgRepo) {
        githubOwner = cfgOwner;
        githubRepo = cfgRepo;
      } else if (cfgCombined && cfgCombined.includes('/')) {
        const parts = cfgCombined.split('/');
        if (parts.length === 2) {
          githubOwner = parts[0];
          githubRepo = parts[1];
        }
      }
    }

    const usingRepo = Boolean(githubOwner && githubRepo);

    // Initialize services
    const linearService = new LinearService(
      config.get('linear.token') as string,
      config.get('linear.defaults.teamId') as string,
      defaultTimeframe
    );
    const openaiService = new OpenAIService(config);

    // Calculate date range based on flags or default timeframe
    let since: Date;
    let until: Date;

    if (flags.since && flags.until) {
      // Parse dates with explicit UTC to avoid timezone issues
      since = new Date(flags.since + 'T00:00:00.000Z');
      until = new Date(flags.until + 'T23:59:59.999Z');
    } else {
      // Use default timeframe from config
      const { startDate, endDate } = config.parseTimeframe(
        defaultTimeframe as string
      );
      since = startDate;
      until = endDate;

      // Set time to start/end of day for default timeframes
      since.setUTCHours(0, 0, 0, 0);
      until.setUTCHours(23, 59, 59, 999);
    }

    // Calculate timeframe for the summary
    const days = Math.ceil(
      (until.getTime() - since.getTime()) / (1000 * 60 * 60 * 24)
    );
    const timeframe = `the past ${days} days`;

    // Show clean summary only for 'summary' format (never for json/markdown)
    if (flags.format === 'summary') {
      if (flags.repo) {
        console.log(
          `== Generating ${githubOwner}/${githubRepo} summary for ${githubUser} (${timeframe})`
        );
      } else {
        console.log(
          `== Generating activity summary for ${githubUser} (${timeframe})`
        );
      }
    }

    try {
      const githubService = createGitHubService();
      const warnings: string[] = [];
      const perspectiveFlag =
        (flags.perspective as 'first-person' | 'third-person' | undefined) ??
        (config.get('summary.perspective') as
          | 'first-person'
          | 'third-person'
          | undefined);

      const perspectiveNameFlag =
        flags['perspective-name'] || (config.get('summary.name') as string);

      // Prepare concurrent tasks
      const githubSpinner = ora(
        usingRepo
          ? `==> Fetching GitHub repository data...`
          : `==> Fetching GitHub activity...`
      ).start();

      const githubPromise = (async () => {
        try {
          if (usingRepo) {
            if (!('fetchEnhancedRepositoryData' in githubService)) {
              throw new Error('Enhanced GitHub service not available');
            }
            const enhancedData =
              await githubService.fetchEnhancedRepositoryData(
                githubOwner!,
                githubRepo!,
                {
                  since,
                  until,
                  author: githubUser as string,
                  includePRs: true,
                  includeIssues: true,
                  includeReviews: true,
                  maxResults: 100,
                }
              );
            githubSpinner.succeed(`== GitHub data collected`);
            return {
              commits: enhancedData.commits.map((ec) => ({
                sha: ec.commit.sha,
                message:
                  ec.commit.commit?.message ??
                  ec.commit.message ??
                  'No message',
                date:
                  ec.commit.commit?.author?.date ??
                  ec.commit.date ??
                  new Date().toISOString(),
                author:
                  (ec.commit.author && 'login' in ec.commit.author
                    ? (ec.commit.author as GitHubUser).login
                    : null) ??
                  ec.commit.commit?.author?.name ??
                  'Unknown',
                repository: `${githubOwner}/${githubRepo}`,
                files: ec.files?.map((f: GitHubFile) => ({
                  filename: f.filename,
                  additions: f.additions,
                  deletions: f.deletions,
                  changes: f.changes,
                })),
                pullRequest: ec.pullRequest
                  ? {
                      number: ec.pullRequest.number,
                      title: ec.pullRequest.title,
                      state: ec.pullRequest.state,
                      reviews: ec.reviews?.map((r: GitHubReview) => ({
                        state: r.state,
                        author:
                          (r.user && 'login' in r.user
                            ? (r.user as GitHubUser).login
                            : null) ?? 'Unknown',
                      })),
                    }
                  : undefined,
              })),
              pullRequests: enhancedData.pullRequests.map((pr) => ({
                title: pr.title,
                state: pr.state,
                createdAt: pr.created_at,
                mergedAt: pr.merged_at ?? undefined,
                author:
                  (pr.user && 'login' in pr.user
                    ? (pr.user as GitHubUser).login
                    : null) ?? 'Unknown',
                url: pr.html_url,
                repository: `${githubOwner}/${githubRepo}`,
                labels: pr.labels?.map((l: GitHubLabel) =>
                  typeof l === 'string' ? l : l.name
                ),
                reviewComments: (pr as { review_comments?: number })
                  .review_comments,
                comments: (pr as { comments?: number }).comments,
              })),
              issues: enhancedData.issues.map((issue) => ({
                title: issue.title,
                state: issue.state,
                createdAt: issue.created_at,
                closedAt: issue.closed_at ?? undefined,
                author:
                  (issue.user && 'login' in issue.user
                    ? (issue.user as GitHubUser).login
                    : null) ?? 'Unknown',
                url: issue.html_url,
                repository: `${githubOwner}/${githubRepo}`,
                labels: issue.labels?.map((l: GitHubLabel) =>
                  typeof l === 'string' ? l : l.name
                ),
              })),
              statistics: enhancedData.statistics,
            } as ActivityData['github'];
          } else {
            if (!('fetchEnhancedUserActivity' in githubService)) {
              throw new Error('Enhanced GitHub service not available');
            }
            // Scale maxResults by timeframe length (cap at 1000 due to GitHub Search API)
            const scaledMax = Math.min(1000, Math.max(100, days * 5));
            const activity = await githubService.fetchEnhancedUserActivity(
              githubUser as string,
              {
                since,
                until,
                maxResults: scaledMax,
              }
            );
            githubSpinner.succeed(`== GitHub activity collected`);
            return {
              commits: [],
              // For user activity, include full raw results to respect timeframe size
              // Use enhanced data only to augment items (do not downselect to top 5)
              pullRequests: activity.pullRequests.map(
                (pr: GitHubPullRequest) => ({
                  title: pr.title,
                  state: pr.state,
                  createdAt: pr.created_at,
                  mergedAt: pr.merged_at ?? undefined,
                  author:
                    (pr.user && 'login' in pr.user
                      ? (pr.user as GitHubUser).login
                      : null) ?? 'Unknown',
                  url: pr.html_url,
                  repository: pr.repository_url
                    ? pr.repository_url.split('/').slice(-2).join('/')
                    : undefined,
                  labels: pr.labels?.map((l: GitHubLabel) =>
                    typeof l === 'string' ? l : l.name
                  ),
                  body: pr.body ?? undefined,
                  enhancedData: pr.enhancedData,
                })
              ),
              issues: activity.issues.map((issue: GitHubIssue) => ({
                title: issue.title,
                state: issue.state,
                createdAt: issue.created_at,
                closedAt: issue.closed_at ?? undefined,
                author:
                  (issue.user && 'login' in issue.user
                    ? (issue.user as GitHubUser).login
                    : null) ?? 'Unknown',
                url: issue.html_url,
                repository: issue.repository_url
                  ? issue.repository_url.split('/').slice(-2).join('/')
                  : undefined,
                labels: issue.labels?.map((l: GitHubLabel) =>
                  typeof l === 'string' ? l : l.name
                ),
                body: issue.body ?? undefined,
                enhancedData: issue.enhancedData,
              })),
              statistics: activity.statistics,
            } as ActivityData['github'];
          }
        } catch (e) {
          githubSpinner.fail(
            `GitHub data collection failed: ${(e as Error).message}`
          );
          warnings.push(
            `GitHub data unavailable: ${(e as Error).message}. Proceeding with partial results.`
          );
          throw e;
        }
      })();

      const linearSpinner = ora(`==> Fetching Linear data...`).start();
      const linearPromise = (async () => {
        try {
          const linearData = await linearService.fetchData({
            assignee: flags['author-linear'],
          });
          linearSpinner.succeed(`== Linear data collected`);
          return {
            issues: linearData.issues,
            activeIssues: linearData.activeIssues,
          } as ActivityData['linear'];
        } catch (e) {
          linearSpinner.fail(
            `Linear data collection failed: ${(e as Error).message}`
          );
          warnings.push(
            `Linear data unavailable: ${(e as Error).message}. Proceeding with partial results.`
          );
          throw e;
        }
      })();

      const [githubResult, linearResult] = await Promise.allSettled([
        githubPromise,
        linearPromise,
      ]);

      if (
        githubResult.status !== 'fulfilled' &&
        linearResult.status !== 'fulfilled'
      ) {
        throw new Error('Both GitHub and Linear requests failed');
      }

      const activityData: ActivityData = {
        github:
          githubResult.status === 'fulfilled' ? githubResult.value : undefined,
        linear:
          linearResult.status === 'fulfilled' ? linearResult.value : undefined,
      };

      // Generate summary
      const aiSpinner = ora(`==> Generating AI summary...`).start();
      const aiSummary = await openaiService.generateActivitySummary(
        activityData,
        timeframe,
        true,
        flags.format as 'summary' | 'markdown',
        { startDate: since, endDate: until },
        perspectiveFlag,
        perspectiveNameFlag ?? undefined,
        flags['template-id'] ?? undefined,
        { fullContext: flags['full-context'] }
      );
      aiSpinner.succeed(`== Summary generated`);

      // Optional timeout/info warning (low-risk UX): surface when response took long
      const approxMs =
        (until.getTime() - since.getTime()) / (1000 * 60 * 60 * 24) > 7
          ? 'long'
          : 'short';
      if (approxMs === 'long') {
        console.warn(
          '!! SUMMARY NOTICE: This summary covered a long timeframe and may take longer depending on data volume.'
        );
      }

      // ASCII art separator only for 'summary' format
      if (flags.format === 'summary') {
        console.log('\n' + '═'.repeat(60));
        console.log(
          '                    == ACTIVITY RECAP ==                    '
        );
        console.log('═'.repeat(60) + '\n');
      }

      if (flags.format === 'json') {
        // Include the exact formatted data fed to the model for downstream UIs
        const formattedData = openaiService.getFormattedActivityData(
          activityData,
          true,
          flags['full-context'] === true
        );
        const finalSummary = flags['no-post']
          ? aiSummary
          : postProcessorService.apply(aiSummary, activityData);
        this.log(
          JSON.stringify(
            {
              summary: finalSummary,
              formattedData,
              data: activityData,
              warnings,
            },
            null,
            2
          )
        );
      } else if (flags.format === 'markdown') {
        // Surface warnings, if any
        warnings.forEach((w) => console.warn(`[WARN] ${w}`));
        const finalSummary = flags['no-post']
          ? aiSummary
          : postProcessorService.apply(aiSummary, activityData);
        this.log(finalSummary);
      } else if (flags.detailed) {
        const formatterService = new FormatterService();
        const formattedSummary = formatterService.formatActivitySummary(
          activityData,
          aiSummary,
          timeframe
        );
        this.log(formattedSummary);
      } else {
        // Surface warnings, if any
        warnings.forEach((w) => console.warn(`[WARN] ${w}`));
        const finalSummary = flags['no-post']
          ? aiSummary
          : postProcessorService.apply(aiSummary, activityData);
        this.log(finalSummary);
      }
    } catch (error) {
      this.error('Failed to generate summary: ' + (error as Error).message);
    }
  }
}
